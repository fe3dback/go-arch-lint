package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"

	"golang.org/x/tools/go/packages"
)

func main() {
	var outPath string
	flag.StringVar(&outPath, "out", "", "output file path")
	flag.StringVar(&outPath, "output", "", "output file path")
	flag.Parse()

	if outPath == "" {
		if _, err := os.Stat("scanner.go"); err == nil {
			outPath = "std_packages.go"
		} else if _, err := os.Stat("internal/services/project/scanner"); err == nil {
			outPath = filepath.Join("internal", "services", "project", "scanner", "std_packages.go")
		} else {
			outPath = "std_packages.go"
		}
	}

	absOutPath, err := filepath.Abs(outPath)
	if err != nil {
		log.Fatalf("failed to resolve absolute output path: %v", err)
	}

	cfg := &packages.Config{
		Mode: packages.NeedName,
		Dir:  os.TempDir(),
	}

	pkgs, err := packages.Load(cfg, "std")
	if err != nil {
		log.Fatalf("failed to load std packages: %v", err)
	}

	pkgSet := make(map[string]struct{})
	for _, pkg := range pkgs {
		if pkg == nil {
			continue
		}
		if pkg.ID != "" {
			pkgSet[pkg.ID] = struct{}{}
		}
		if pkg.PkgPath != "" {
			pkgSet[pkg.PkgPath] = struct{}{}
		}
	}

	list := make([]string, 0, len(pkgSet))
	for name := range pkgSet {
		list = append(list, name)
	}
	sort.Strings(list)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/gen-std-packages. DO NOT EDIT.\n\n")
	buf.WriteString("package scanner\n\n")
	buf.WriteString("var knownStdPackages = []string{\n")
	for _, name := range list {
		fmt.Fprintf(&buf, "\t%q,\n", name)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("failed to format generated code: %v", err)
	}

	if err := os.WriteFile(absOutPath, formatted, 0o600); err != nil {
		log.Fatalf("failed to write output file: %v", err)
	}

	log.Printf("generated %d standard packages in %s", len(list), absOutPath)
}
